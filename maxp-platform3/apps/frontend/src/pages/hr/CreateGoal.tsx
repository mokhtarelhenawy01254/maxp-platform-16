type GoalType = "COMPANY" | "DEPARTMENT" | "PROJECT" | "EMPLOYEE";
type GoalStatus = "PENDING" | "IN_PROGRESS" | "COMPLETED" | "CANCELLED";
type GoalPriority = "LOW" | "MEDIUM" | "HIGH" | "URGENT";

interface EmployeeOption {
  id: string;
  firstName: string;
  lastName: string;
  employeeNumber?: string | null;
}

interface DepartmentOption {
  id: string;
  name: string;
}

interface ProjectOption {
  id: string;
  name: string;
}

interface TaskOption {
  id: string;
  title: string;
  status?: string;
  measurementType?: string;
  metricTargetValue?: number | null;
}

interface ParentGoalOption {
  id: string;
  title: string;
  goalType: GoalType | "DAILY";
  projectId?: string | null;
}

interface AssignmentDraft {
  id?: string;
  employeeId: string;
  title: string;
  targetValue: string;
  autoGenerateDaily: boolean;
}

interface GoalDetails {
  id: string;
  title: string;
  description?: string | null;
  goalType: GoalType | "DAILY";
  status: GoalStatus;
  priority: GoalPriority;
  targetValue: number;
  currentValue: number;
  unit?: string | null;
  startDate: string;
  endDate: string;
  project?: ProjectOption | null;
  department?: DepartmentOption | null;
  employee?: EmployeeOption | null;
  parentGoal?: ParentGoalOption | null;
  autoGenerateDaily: boolean;
  childGoals?: Array<{
    id: string;
    title: string;
    goalType: GoalType | "DAILY";
    targetValue: number;
    employee?: EmployeeOption | null;
    autoGenerateDaily?: boolean;
  }>;
  tasks?: TaskOption[];
}

interface GoalFormState {
  title: string;
  description: string;
  goalType: GoalType;
  status: GoalStatus;
  priority: GoalPriority;
  targetValue: string;
  currentValue: string;
  unit: string;
  startDate: string;
  endDate: string;
  projectId: string;
  departmentId: string;
  employeeId: string;
  parentGoalId: string;
  autoGenerateDaily: boolean;
  linkedTaskIds: string[];
  assignments: AssignmentDraft[];
}

