const main = async () => {
  await fs.mkdir(OUTPUT_DIR, { recursive: true });
  const results = [];
  const requestedScenarios = process.argv
    .flatMap((arg, index, args) => {
      if (arg === "--scenario" && args[index + 1]) {
        return [args[index + 1]];
      }

      if (arg.startsWith("--scenario=")) {
        return [arg.slice("--scenario=".length)];
      }

      return [];
    })
    .map((value) => value.toLowerCase());
  const scenariosToRun =
    requestedScenarios.length === 0
      ? SCENARIOS
      : SCENARIOS.filter((scenario) =>
          requestedScenarios.some((requested) =>
            scenario.name.toLowerCase().includes(requested),
          ),
        );
  const browser = await chromium.launch({ headless: true });

  try {
    for (const scenario of scenariosToRun) {
      await withScenario({
        browser,
        name: scenario.name,
        description: scenario.description,
        stateOverrides: scenario.stateOverrides,
        run: scenario.run,
        results,
      });
    }
  } finally {
    await browser.close();
  }

  await writeResults(results);

  const failed = results.filter((result) => result.status !== "passed");
  if (failed.length > 0) {
    console.error(JSON.stringify({ results }, null, 2));
    process.exit(1);
  }

  console.log(JSON.stringify({ results }, null, 2));
};

await main();
