import React, { useEffect, useMemo, useState } from "react";
import { useNavigate } from "react-router-dom";
import {
  ArrowRight,
  Briefcase,
  CalendarRange,
  ChevronLeft,
  Filter,
  FolderKanban,
  Plus,
  Target,
  Users,
} from "lucide-react";

import {
  BusinessPageHero,
  BusinessPageShell,
  BusinessSectionPanel,
} from "../../components/business/BusinessSurface";
import { Badge } from "../../components/ui/badge";
import { Button } from "../../components/ui/button";
import { Input } from "../../components/ui/input";
import { Progress } from "../../components/ui/progress";
import { Switch } from "../../components/ui/switch";
import api from "../../services/api";
import { toast } from "sonner";
import { tToast } from "../../utils/i18n-toast";

type GoalType = "COMPANY" | "DEPARTMENT" | "PROJECT" | "EMPLOYEE" | "DAILY";

interface GoalUser {
  id: string;
  firstName: string;
  lastName: string;
  department?: {
    id: string;
    name: string;
  } | null;
}

interface GoalProject {
  id: string;
  name: string;
}

interface GoalTask {
  id: string;
  title: string;
}

interface GoalRecord {
  id: string;
  title: string;
  description?: string | null;
  goalType: GoalType;
  priority: string;
  targetValue: number;
  currentValue: number;
  progress: number;
  status: string;
  unit?: string | null;
  startDate: string;
  endDate: string;
  goalDate?: string | null;
  autoGenerateDaily: boolean;
  project?: GoalProject | null;
  employee?: GoalUser | null;
  department?: {
    id: string;
    name: string;
  } | null;
  parentGoal?: {
    id: string;
    title: string;
    goalType: GoalType;
  } | null;
  childGoals?: Array<{
    id: string;
    title: string;
    goalType: GoalType;
    progress: number;
    targetValue: number;
    currentValue: number;
    goalDate?: string | null;
    user?: GoalUser | null;
    employee?: GoalUser | null;
  }>;
  tasks?: GoalTask[];
}

interface GoalStats {
  total: number;
  completed: number;
  completionRate: number;
  averageProgress: number;
  byType?: Array<{ goalType: GoalType; _count: number }>;
}

interface ProjectOption {
  id: string;
  name: string;
}

const GOAL_TYPE_LABELS: Record<GoalType, string> = {
  COMPANY: "هدف عام",
  DEPARTMENT: "هدف قسم",
  PROJECT: "هدف مشروع",
  EMPLOYEE: "هدف موظف",
  DAILY: "هدف يومي",
};

const STATUS_STYLES: Record<string, string> = {
  PENDING: "bg-amber-50 text-amber-700 ring-amber-200",
  IN_PROGRESS: "bg-blue-50 text-blue-700 ring-blue-200",
  COMPLETED: "bg-emerald-50 text-emerald-700 ring-emerald-200",
  CANCELLED: "bg-rose-50 text-rose-700 ring-rose-200",
};

const priorityLabel = (priority?: string) => {
  switch (priority) {
    case "URGENT":
      return "عاجل";
    case "HIGH":
      return "عال";
    case "LOW":
      return "منخفض";
    default:
      return "متوسط";
  }
};

const statusLabel = (status?: string) => {
  switch (status) {
    case "COMPLETED":
      return "مكتمل";
    case "IN_PROGRESS":
      return "قيد التنفيذ";
    case "CANCELLED":
      return "ملغي";
    default:
      return "معلق";
  }
};

const formatGoalDateRange = (goal: GoalRecord) => {
  if (goal.goalType === "DAILY" && goal.goalDate) {
    return new Date(goal.goalDate).toLocaleDateString("ar-EG");
  }

  return `${new Date(goal.startDate).toLocaleDateString("ar-EG")} - ${new Date(
    goal.endDate,
  ).toLocaleDateString("ar-EG")}`;
};

const getGoalOwnerLabel = (goal: GoalRecord) => {
  if (goal.employee) {
    return `${goal.employee.firstName} ${goal.employee.lastName}`;
  }

  if (goal.project) {
    return goal.project.name;
  }

  if (goal.department) {
    return goal.department.name;
  }

  return "على مستوى الشركة";
};

const ensureArray = <T,>(value: unknown): T[] =>
  Array.isArray(value) ? (value as T[]) : [];

const Goals: React.FC = () => {
  const navigate = useNavigate();
  const [loading, setLoading] = useState(true);
  const [goals, setGoals] = useState<GoalRecord[]>([]);
  const [stats, setStats] = useState<GoalStats | null>(null);
  const [projects, setProjects] = useState<ProjectOption[]>([]);
  const [goalType, setGoalType] = useState<"ALL" | GoalType>("ALL");
  const [status, setStatus] = useState("ALL");
  const [projectId, setProjectId] = useState("");
  const [includeDaily, setIncludeDaily] = useState(false);
  const [search, setSearch] = useState("");

  useEffect(() => {
    void fetchProjects();
  }, []);

  useEffect(() => {
    void fetchGoals();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [goalType, status, projectId, includeDaily]);

  const fetchProjects = async () => {
    try {
      const response = await api.get("/projects");
      setProjects(
        ensureArray<ProjectOption>(
          response.data?.data?.projects ||
            response.data?.data ||
            response.data?.projects,
        ),
      );
    } catch (error) {
      console.error("Error fetching projects:", error);
    }
  };

  const fetchGoals = async () => {
    try {
      setLoading(true);
      const params = new URLSearchParams();

      if (goalType !== "ALL") {
        params.set("goalType", goalType);
      }

      if (status !== "ALL") {
        params.set("status", status);
      }

      if (projectId) {
        params.set("projectId", projectId);
      }

      if (!includeDaily && goalType !== "DAILY") {
        params.set("includeDaily", "false");
      }

      const query = params.toString();
      const [goalsResponse, statsResponse] = await Promise.all([
        api.get(`/tasks/goals${query ? `?${query}` : ""}`),
        api.get(`/tasks/goals/stats${query ? `?${query}` : ""}`),
      ]);

      setGoals(
        ensureArray<GoalRecord>(
          goalsResponse.data?.goals ||
            goalsResponse.data?.data ||
            goalsResponse.data?.data?.goals,
        ),
      );
      setStats(statsResponse.data.stats || null);
    } catch (error) {
      console.error("Error fetching goals:", error);
      tToast.error("hr_Goals.unable_load_2181");
    } finally {
      setLoading(false);
    }
  };

  const filteredGoals = useMemo(() => {
    const normalizedSearch = search.trim().toLowerCase();

    if (!normalizedSearch) {
      return goals;
    }

    return goals.filter((goal) => {
      const owner = getGoalOwnerLabel(goal).toLowerCase();
      return (
        goal.title.toLowerCase().includes(normalizedSearch) ||
        (goal.description || "").toLowerCase().includes(normalizedSearch) ||
        owner.includes(normalizedSearch)
      );
    });
  }, [goals, search]);

  const dailyGoalsCount = useMemo(
    () => goals.filter((goal) => goal.goalType === "DAILY").length,
    [goals],
  );

  if (loading) {
    return (
      <div className="flex min-h-[60vh] items-center justify-center">
        <div className="h-12 w-12 animate-spin rounded-full border-b-2 border-primary" />
      </div>
    );
  }

  return (
    <BusinessPageShell className="space-y-6 p-4 md:p-6" dir="rtl">
      <BusinessPageHero
        eyebrow="الأعمال"
        title="إدارة الأهداف"
        description="من هنا نربط هدف المشروع بالموظفين والأيام والمهام، ونراقب التقدم الفعلي بدل الأرقام المعزولة."
        actions={
          <Button className="rounded-xl" onClick={() => navigate("/goals/new")}>
            <Plus className="ml-2 h-4 w-4" />
            هدف جديد
          </Button>
        }
      />

      <section className="grid gap-4 md:grid-cols-2 xl:grid-cols-4">
        <div className="rounded-3xl border border-border/70 bg-background p-5">
          <div className="text-sm text-muted-foreground">إجمالي الأهداف</div>
          <div className="mt-2 text-3xl font-semibold">{stats?.total || 0}</div>
        </div>
        <div className="rounded-3xl border border-border/70 bg-background p-5">
          <div className="text-sm text-muted-foreground">مكتمل</div>
          <div className="mt-2 text-3xl font-semibold">
            {stats?.completed || 0}
          </div>
          <div className="mt-1 text-sm text-muted-foreground">
            {Number(stats?.completionRate || 0).toFixed(1)}%
          </div>
        </div>
        <div className="rounded-3xl border border-border/70 bg-background p-5">
          <div className="text-sm text-muted-foreground">متوسط التقدم</div>
          <div className="mt-2 text-3xl font-semibold">
            {Number(stats?.averageProgress || 0).toFixed(1)}%
          </div>
          <Progress
            value={Math.max(0, Math.min(100, Number(stats?.averageProgress || 0)))}
            className="mt-3"
          />
        </div>
        <div className="rounded-3xl border border-border/70 bg-background p-5">
          <div className="text-sm text-muted-foreground">الأهداف اليومية</div>
          <div className="mt-2 text-3xl font-semibold">{dailyGoalsCount}</div>
          <div className="mt-1 text-sm text-muted-foreground">
            تظهر تلقائيًا عند توزيع أهداف الموظفين
          </div>
        </div>
      </section>

      <BusinessSectionPanel
        title="التصفية والعرض"
        description="فلتر حسب نوع الهدف أو المشروع أو الحالة، وقرر هل تريد رؤية الأهداف اليومية مع باقي السلسلة."
        contentClassName="space-y-4"
      >
        <div className="grid gap-3 lg:grid-cols-[1.2fr_repeat(3,minmax(0,1fr))]">
          <div className="relative">
            <Filter className="pointer-events-none absolute right-3 top-1/2 h-4 w-4 -translate-y-1/2 text-muted-foreground" />
            <Input
              data-testid="goals-search-input"
              value={search}
              onChange={(event) => setSearch(event.target.value)}
              placeholder="ابحث بعنوان الهدف أو المسؤول"
              className="rounded-2xl pr-10"
            />
          </div>

          <select
            data-testid="goals-type-filter"
            value={goalType}
            onChange={(event) => setGoalType(event.target.value as "ALL" | GoalType)}
            className="h-10 rounded-2xl border border-input bg-background px-3 text-sm"
          >
            <option value="ALL">كل الأنواع</option>
            <option value="PROJECT">أهداف المشاريع</option>
            <option value="EMPLOYEE">أهداف الموظفين</option>
            <option value="DEPARTMENT">أهداف الأقسام</option>
            <option value="COMPANY">الأهداف العامة</option>
            <option value="DAILY">الأهداف اليومية</option>
          </select>

          <select
            data-testid="goals-status-filter"
            value={status}
            onChange={(event) => setStatus(event.target.value)}
            className="h-10 rounded-2xl border border-input bg-background px-3 text-sm"
          >
            <option value="ALL">كل الحالات</option>
            <option value="PENDING">معلق</option>
            <option value="IN_PROGRESS">قيد التنفيذ</option>
            <option value="COMPLETED">مكتمل</option>
            <option value="CANCELLED">ملغي</option>
          </select>

          <select
            data-testid="goals-project-filter"
            value={projectId}
            onChange={(event) => setProjectId(event.target.value)}
            className="h-10 rounded-2xl border border-input bg-background px-3 text-sm"
          >
            <option value="">كل المشاريع</option>
            {projects.map((project) => (
              <option key={project.id} value={project.id}>
                {project.name}
              </option>
            ))}
          </select>
        </div>

        <div className="flex flex-wrap items-center justify-between gap-3 rounded-2xl border border-border/70 bg-muted/20 px-4 py-3">
          <div className="space-y-1">
            <div className="text-sm font-medium">إظهار الأهداف اليومية</div>
            <div className="text-xs text-muted-foreground">
              مفيد عند مراجعة التوزيع اليومي وتحديثات قبل الانصراف.
            </div>
          </div>

          <div className="flex items-center gap-3">
            <span className="text-sm text-muted-foreground">
              {includeDaily ? "مفعّل" : "مخفي"}
            </span>
            <Switch
              data-testid="goals-include-daily-switch"
              checked={includeDaily}
              onCheckedChange={(checked) => setIncludeDaily(Boolean(checked))}
            />
          </div>
        </div>
      </BusinessSectionPanel>

      <BusinessSectionPanel
        title="شبكة الأهداف"
        description="كل صف يعرض الهدف نفسه، التقدم الفعلي، وصورته داخل التسلسل الأب والابن."
        contentClassName="space-y-4"
      >
        {filteredGoals.length === 0 ? (
          <div className="rounded-3xl border border-dashed border-border/70 bg-muted/10 px-6 py-12 text-center">
            <Target className="mx-auto h-10 w-10 text-muted-foreground" />
            <h3 className="mt-4 text-lg font-semibold">لا توجد أهداف مطابقة</h3>
            <p className="mt-2 text-sm text-muted-foreground">
              غيّر الفلاتر الحالية أو ابدأ بإضافة هدف مشروع جديد وتوزيعه على الفريق.
            </p>
          </div>
        ) : (
          <div className="space-y-3">
            {filteredGoals.map((goal) => (
              <article
                key={goal.id}
                className="rounded-3xl border border-border/70 bg-background p-4 transition-colors hover:border-primary/30"
              >
                <div className="flex flex-col gap-4 xl:flex-row xl:items-start xl:justify-between">
                  <div className="space-y-3">
                    <div className="flex flex-wrap items-center gap-2">
                      <Badge variant="outline" className="rounded-full">
                        {GOAL_TYPE_LABELS[goal.goalType]}
                      </Badge>
                      <span
                        className={`rounded-full px-3 py-1 text-xs font-medium ring-1 ${
                          STATUS_STYLES[goal.status] || "bg-muted text-foreground ring-border"
                        }`}
                      >
                        {statusLabel(goal.status)}
                      </span>
                      <span className="rounded-full bg-muted px-3 py-1 text-xs text-muted-foreground">
                        أولوية {priorityLabel(goal.priority)}
                      </span>
                    </div>

                    <div>
                      <h3 className="text-lg font-semibold">{goal.title}</h3>
                      {goal.description ? (
                        <p className="mt-1 text-sm text-muted-foreground">
                          {goal.description}
                        </p>
                      ) : null}
                    </div>

                    <div className="flex flex-wrap gap-3 text-sm text-muted-foreground">
                      <span className="inline-flex items-center gap-2">
                        <Briefcase className="h-4 w-4" />
                        {getGoalOwnerLabel(goal)}
                      </span>
                      <span className="inline-flex items-center gap-2">
                        <CalendarRange className="h-4 w-4" />
                        {formatGoalDateRange(goal)}
                      </span>
                      {goal.parentGoal ? (
                        <span className="inline-flex items-center gap-2">
                          <ChevronLeft className="h-4 w-4" />
                          يتبع: {goal.parentGoal.title}
                        </span>
                      ) : null}
                    </div>
                  </div>

                  <div className="flex shrink-0 items-center gap-2">
                    <Button
                      variant="outline"
                      className="rounded-xl"
                      onClick={() => navigate(`/goals/${goal.id}`)}
                    >
                      <ArrowRight className="ml-2 h-4 w-4" />
                      فتح
                    </Button>
                  </div>
                </div>

                <div className="mt-4 grid gap-4 xl:grid-cols-[minmax(0,1.6fr)_minmax(0,1fr)]">
                  <div className="space-y-2">
                    <div className="flex items-center justify-between text-sm">
                      <span className="text-muted-foreground">التقدم</span>
                      <span className="font-medium">
                        {Number(goal.progress || 0).toFixed(1)}%
                      </span>
                    </div>
                    <Progress value={goal.progress || 0} />
                    <div className="flex flex-wrap items-center gap-4 text-sm text-muted-foreground">
                      <span>
                        الحالي:{" "}
                        <strong className="text-foreground">
                          {Number(goal.currentValue || 0).toLocaleString("ar-EG")}
                        </strong>
                      </span>
                      <span>
                        المستهدف:{" "}
                        <strong className="text-foreground">
                          {Number(goal.targetValue || 0).toLocaleString("ar-EG")}
                        </strong>
                      </span>
                      {goal.unit ? (
                        <span>
                          الوحدة:{" "}
                          <strong className="text-foreground">{goal.unit}</strong>
                        </span>
                      ) : null}
                    </div>
                  </div>

                  <div className="grid gap-3 sm:grid-cols-3 xl:grid-cols-1">
                    <div className="rounded-2xl border border-border/70 bg-muted/10 px-4 py-3">
                      <div className="flex items-center gap-2 text-sm text-muted-foreground">
                        <Users className="h-4 w-4" />
                        أبناء الهدف
                      </div>
                      <div className="mt-1 text-xl font-semibold">
                        {goal.childGoals?.length || 0}
                      </div>
                    </div>
                    <div className="rounded-2xl border border-border/70 bg-muted/10 px-4 py-3">
                      <div className="flex items-center gap-2 text-sm text-muted-foreground">
                        <FolderKanban className="h-4 w-4" />
                        مهام مرتبطة
                      </div>
                      <div className="mt-1 text-xl font-semibold">
                        {goal.tasks?.length || 0}
                      </div>
                    </div>
                    <div className="rounded-2xl border border-border/70 bg-muted/10 px-4 py-3">
                      <div className="text-sm text-muted-foreground">
                        التوليد اليومي
                      </div>
                      <div className="mt-1 text-sm font-medium text-foreground">
                        {goal.autoGenerateDaily ? "مفعّل" : "غير مفعّل"}
                      </div>
                    </div>
                  </div>
                </div>

                {goal.childGoals && goal.childGoals.length > 0 ? (
                  <div className="mt-4 space-y-2 rounded-2xl border border-border/60 bg-muted/10 p-3">
                    <div className="text-sm font-medium">لقطة من التسلسل</div>
                    <div className="space-y-2">
                      {goal.childGoals.slice(0, 3).map((childGoal) => (
                        <div
                          key={childGoal.id}
                          className="flex flex-wrap items-center justify-between gap-3 rounded-2xl bg-background px-3 py-2"
                        >
                          <div className="text-sm">
                            <span className="font-medium">{childGoal.title}</span>
                            <span className="mr-2 text-muted-foreground">
                              {GOAL_TYPE_LABELS[childGoal.goalType]}
                            </span>
                          </div>
                          <div className="text-sm text-muted-foreground">
                            {Number(childGoal.currentValue || 0).toLocaleString("ar-EG")}
                            {" / "}
                            {Number(childGoal.targetValue || 0).toLocaleString("ar-EG")}
                            {" • "}
                            {Number(childGoal.progress || 0).toFixed(0)}%
                          </div>
                        </div>
                      ))}
                    </div>
                  </div>
                ) : null}
              </article>
            ))}
          </div>
        )}
      </BusinessSectionPanel>
    </BusinessPageShell>
  );
};

export default Goals;
