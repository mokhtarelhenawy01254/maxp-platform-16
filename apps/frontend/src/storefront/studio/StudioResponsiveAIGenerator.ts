export interface ResponsiveRules {
  mobileColumns?: number;
  tabletColumns?: number;
  mobilePadding?: string;
  tabletPadding?: string;
  mobileAlignment?: "center" | "right" | "left";
  stackDirectionMobile?: "col" | "row";
  mobileSpacing?: "compact" | "normal";
  hideOnMobile?: boolean;
}

/**
 * Responsive AI Engine (Wix Studio 2026 style)
 * Generates optimized mobile & tablet rules based on section type & structure
 */
export function generateResponsiveSectionRules(
  sectionType: string,
  currentSettings: Record<string, unknown> = {}
): Record<string, unknown> {
  const patch: Record<string, unknown> = {
    ...currentSettings,
    responsiveGeneratedAt: Date.now(),
    responsiveAutoGenerated: true,
  };

  switch (sectionType) {
    case "hero-banner":
    case "hero":
    case "split-hero":
    case "cinematic-banner":
      patch["mobilePadding"] = "20px 16px";
      patch["tabletPadding"] = "32px 24px";
      patch["mobileAlignment"] = "center";
      patch["mobileHeight"] = "auto";
      patch["stackDirectionMobile"] = "col";
      patch["ctaFullWidthMobile"] = true;
      break;

    case "featured-products":
    case "product-grid":
    case "product-slider":
    case "recent-products":
    case "flash-sale":
      patch["mobileColumns"] = 2;
      patch["tabletColumns"] = 3;
      patch["columns"] = currentSettings["columns"] || 4;
      patch["mobileGap"] = "8px";
      patch["mobilePadding"] = "16px 12px";
      patch["showQuickBuyMobile"] = true;
      break;

    case "features-bar":
    case "trust-badges":
      patch["mobileColumns"] = 2;
      patch["tabletColumns"] = 4;
      patch["mobilePadding"] = "12px 14px";
      patch["mobileIconSize"] = "small";
      break;

    case "customer-reviews":
    case "testimonials-slider":
      patch["mobileColumns"] = 1;
      patch["tabletColumns"] = 2;
      patch["mobilePadding"] = "18px 14px";
      patch["mobileAutoScroll"] = true;
      break;

    case "sale-countdown":
    case "promotion-banner":
    case "deal-of-the-day":
    case "coupon-strip":
      patch["mobilePadding"] = "14px 12px";
      patch["mobileLayout"] = "stacked";
      patch["mobileTimerSize"] = "compact";
      break;

    default:
      patch["mobilePadding"] = "16px 14px";
      patch["tabletPadding"] = "24px 20px";
      patch["stackDirectionMobile"] = "col";
      break;
  }

  return patch;
}
