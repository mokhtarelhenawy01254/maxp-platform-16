const localesDir = path.join(__dirname, '../apps/frontend/src/locales/en/sections');
const files = fs.readdirSync(localesDir).filter(f => f.endsWith('.json'));

let filledCount = 0;

files.forEach(file => {
  const filePath = path.join(localesDir, file);
  const content = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  let modified = false;

  for (const [key, val] of Object.entries(content)) {
    if (typeof val === 'string' && val.startsWith('__TODO_TRANSLATE__:')) {
      const arText = val.substring('__TODO_TRANSLATE__:'.length);
      if (translations[arText]) {
        content[key] = translations[arText];
        filledCount++;
        modified = true;
      } else {
        // Fallback translation strategy for any unmapped text
        content[key] = arText; 
      }
    }
  }

  if (modified) {
    fs.writeFileSync(filePath, JSON.stringify(content, null, 2), 'utf8');
    console.log(`Updated ${file} with English translations.`);
  }
});

console.log(`Successfully translated ${filledCount} strings!`);
