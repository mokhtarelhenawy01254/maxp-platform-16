const withScenario = async ({
  browser,
  name,
  description,
  stateOverrides = {},
  run,
  results,
}) => {
  const state = createScenarioState(stateOverrides);
  const captures = createCaptures();
  const context = await browser.newContext({
    viewport: { width: 1440, height: 1600 },
  });
  const pageErrors = [];
  const consoleErrors = [];

  await setAuthStorage(context, state.user);
  await context.route("**/api/v1/**", createApiHandler(state, captures));

  const page = await context.newPage();
  page.on("pageerror", (error) => {
    pageErrors.push({ message: error.message, stack: error.stack });
  });
  page.on("console", (message) => {
    if (message.type() === "error") {
      consoleErrors.push(message.text());
    }
  });

  const safeName = name.replace(/[^a-z0-9-]/gi, "_").toLowerCase();
  const screenshotPath = path.join(OUTPUT_DIR, `${safeName}.png`);

  try {
    await run({ page, state, captures });
    assert.equal(
      pageErrors.length,
      0,
      `Page errors found: ${pageErrors.map((item) => item.message).join(" | ")}`,
    );
    await page.screenshot({ path: screenshotPath, fullPage: true });
    results.push({
      name,
      description,
      status: "passed",
      screenshotPath,
      notes: [],
    });
    await writeResults(results);
  } catch (error) {
    await page.screenshot({
      path: screenshotPath.replace(/\.png$/, "-failed.png"),
      fullPage: true,
    });
    results.push({
      name,
      description,
      status: "failed",
      screenshotPath: screenshotPath.replace(/\.png$/, "-failed.png"),
      notes: [
        error instanceof Error ? error.message : String(error),
        ...pageErrors.map((item) => item.message),
        ...consoleErrors,
      ].filter(Boolean),
    });
    await writeResults(results);
  } finally {
    await context.close();
  }
};

