const createEmptyAssignment = (): AssignmentDraft => ({
  employeeId: "",
  title: "",
  targetValue: "",
  autoGenerateDaily: true,
});

const createInitialFormState = (): GoalFormState => ({
  title: "",
  description: "",
  goalType: "PROJECT",
  status: "PENDING",
  priority: "MEDIUM",
  targetValue: "",
  currentValue: "0",
  unit: "طلب",
  startDate: "",
  endDate: "",
  projectId: "",
  departmentId: "",
  employeeId: "",
  parentGoalId: "",
  autoGenerateDaily: true,
  linkedTaskIds: [],
  assignments: [createEmptyAssignment()],
});

const toInputDate = (value?: string | null) => {
  if (!value) {
    return "";
  }

  const date = new Date(value);
  if (Number.isNaN(date.getTime())) {
    return "";
  }

  return date.toISOString().split("T")[0];
};

const toNumber = (value: string) => {
  const parsed = Number.parseFloat(value);
  return Number.isFinite(parsed) ? parsed : 0;
};

const ensureArray = <T,>(value: unknown): T[] =>
  Array.isArray(value) ? (value as T[]) : [];

const getHydrationErrorMessage = (error: unknown, isEdit: boolean) => {
  const apiError = error as {
    response?: {
      status?: number;
    };
  };

  if (apiError.response?.status === 404) {
    return "الهدف المطلوب غير موجود أو تم حذفه";
  }

  if (apiError.response?.status === 403) {
    return isEdit
      ? "لا تملك صلاحية الوصول إلى هذا الهدف"
      : "لا تملك صلاحية الوصول إلى هذه البيانات";
  }

  return isEdit ? "تعذر تحميل بيانات الهدف" : "تعذر تحميل بيانات الصفحة";
};

const getEmployeeLabel = (employee: EmployeeOption) => {
  const fullName = `${employee.firstName || ""} ${employee.lastName || ""}`.trim();
  return employee.employeeNumber
    ? `${fullName} - ${employee.employeeNumber}`
    : fullName;
};

const CreateGoal: React.FC = () => {
  const { id } = useParams<{ id?: string }>();
  const navigate = useNavigate();
  const isEdit = Boolean(id);

  const [loading, setLoading] = useState(false);
  const [fetching, setFetching] = useState(true);
  const [loadError, setLoadError] = useState<string | null>(null);
  const [form, setForm] = useState<GoalFormState>(createInitialFormState);
  const [goalDetails, setGoalDetails] = useState<GoalDetails | null>(null);
  const [employees, setEmployees] = useState<EmployeeOption[]>([]);
  const [departments, setDepartments] = useState<DepartmentOption[]>([]);
  const [projects, setProjects] = useState<ProjectOption[]>([]);
  const [tasks, setTasks] = useState<TaskOption[]>([]);
  const [parentGoals, setParentGoals] = useState<ParentGoalOption[]>([]);
  const [taskSearch, setTaskSearch] = useState("");

  useEffect(() => {
    void hydratePage();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [id]);

  const hydratePage = async () => {
    try {
      setFetching(true);
      setLoadError(null);

      const [employeesResponse, departmentsResponse, projectsResponse, tasksResponse, parentGoalsResponse] =
        await Promise.all([
          api.get("/hr/employees"),
          api.get("/hr/departments"),
          api.get("/projects"),
          api.get("/tasks?limit=200"),
          api.get("/tasks/goals?includeDaily=false"),
        ]);

      const employeeRows =
        employeesResponse.data?.employees ||
        employeesResponse.data?.data ||
        employeesResponse.data ||
        [];
      const departmentRows =
        departmentsResponse.data?.departments ||
        departmentsResponse.data?.data ||
        departmentsResponse.data ||
        [];
      const projectRows =
        projectsResponse.data?.data ||
        projectsResponse.data?.projects ||
        [];
      const taskRows =
        tasksResponse.data?.data ||
        tasksResponse.data?.tasks ||
        [];
      const parentGoalRows =
        parentGoalsResponse.data?.goals ||
        parentGoalsResponse.data?.data ||
        [];

      setEmployees(ensureArray<EmployeeOption>(employeeRows));
      setDepartments(ensureArray<DepartmentOption>(departmentRows));
      setProjects(ensureArray<ProjectOption>(projectRows));
      setTasks(
        ensureArray<TaskOption>(
          taskRows ||
            tasksResponse.data?.tasks ||
            tasksResponse.data?.data?.tasks ||
            tasksResponse.data?.data?.items,
        ),
      );
      setParentGoals(ensureArray<ParentGoalOption>(parentGoalRows));

      if (!isEdit) {
        setGoalDetails(null);
        setForm({
          ...createInitialFormState(),
          startDate: toInputDate(new Date().toISOString()),
          endDate: toInputDate(new Date().toISOString()),
        });
        return;
      }

      const goalResponse = await api.get(`/tasks/goals/${id}`);
      const goal = goalResponse.data?.goal as GoalDetails;

      if (!goal) {
        const errorMessage = "الهدف المطلوب غير موجود أو تم حذفه";
        setGoalDetails(null);
        setLoadError(errorMessage);
        toast.error(errorMessage);
        return;
      }

      setGoalDetails(goal);
      setForm({
        title: goal.title || "",
        description: goal.description || "",
        goalType:
          goal.goalType === "DAILY" ? "EMPLOYEE" : (goal.goalType as GoalType),
        status: goal.status,
        priority: goal.priority,
        targetValue: String(goal.targetValue ?? ""),
        currentValue: String(goal.currentValue ?? 0),
        unit: goal.unit || "",
        startDate: toInputDate(goal.startDate),
        endDate: toInputDate(goal.endDate),
        projectId: goal.project?.id || "",
        departmentId: goal.department?.id || "",
        employeeId: goal.employee?.id || "",
        parentGoalId: goal.parentGoal?.id || "",
        autoGenerateDaily: Boolean(goal.autoGenerateDaily),
        linkedTaskIds: (goal.tasks || []).map((task) => task.id),
        assignments:
          goal.goalType === "PROJECT"
            ? (goal.childGoals || [])
                .filter((childGoal) => childGoal.goalType === "EMPLOYEE")
                .map((childGoal) => ({
                  id: childGoal.id,
                  employeeId: childGoal.employee?.id || "",
                  title: childGoal.title || "",
                  targetValue: String(childGoal.targetValue ?? ""),
                  autoGenerateDaily: Boolean(
                    (childGoal as { autoGenerateDaily?: boolean }).autoGenerateDaily ??
                      goal.autoGenerateDaily,
                  ),
                }))
            : [createEmptyAssignment()],
      });
    } catch (error) {
      console.error("Error hydrating goal form:", error);
      const errorMessage = getHydrationErrorMessage(error, isEdit);
      setGoalDetails(null);
      setLoadError(errorMessage);
      toast.error(errorMessage);
    } finally {
      setFetching(false);
    }
  };

  const filteredTaskOptions = useMemo(() => {
    const normalizedSearch = taskSearch.trim().toLowerCase();
    const taskOptions = ensureArray<TaskOption>(tasks);

    return taskOptions.filter((task) => {
      if (form.projectId && (task as { projectId?: string }).projectId !== form.projectId) {
        return false;
      }

      if (!normalizedSearch) {
        return true;
      }

      return task.title.toLowerCase().includes(normalizedSearch);
    });
  }, [form.projectId, taskSearch, tasks]);

  const availableParentGoals = useMemo(
    () =>
      parentGoals.filter(
        (goal) =>
          goal.goalType !== "DAILY" &&
          goal.id !== id &&
          (!form.projectId ||
            goal.goalType !== "PROJECT" ||
            goal.projectId === form.projectId),
      ),
    [form.projectId, id, parentGoals],
  );

  const assignmentTargetTotal = useMemo(
    () =>
      form.assignments.reduce(
        (sum, assignment) => sum + toNumber(assignment.targetValue || "0"),
        0,
      ),
    [form.assignments],
  );

  const targetValueNumber = useMemo(
    () => toNumber(form.targetValue || "0"),
    [form.targetValue],
  );

  const assignmentCoverage = targetValueNumber
    ? Math.min(100, (assignmentTargetTotal / targetValueNumber) * 100)
    : 0;

  const linkedTasks = useMemo(
    () =>
      ensureArray<TaskOption>(tasks).filter((task) =>
        form.linkedTaskIds.includes(task.id),
      ),
    [form.linkedTaskIds, tasks],
  );

  const setField = <K extends keyof GoalFormState>(
    key: K,
    value: GoalFormState[K],
  ) => {
    setForm((previous) => ({ ...previous, [key]: value }));
  };

  const updateAssignment = (
    index: number,
    key: keyof AssignmentDraft,
    value: string | boolean,
  ) => {
    setForm((previous) => ({
      ...previous,
      assignments: previous.assignments.map((assignment, assignmentIndex) =>
        assignmentIndex === index
          ? { ...assignment, [key]: value }
          : assignment,
      ),
    }));
  };

  const addAssignment = () => {
    setForm((previous) => ({
      ...previous,
      assignments: [...previous.assignments, createEmptyAssignment()],
    }));
  };

  const removeAssignment = (index: number) => {
    setForm((previous) => ({
      ...previous,
      assignments:
        previous.assignments.length === 1
          ? [createEmptyAssignment()]
          : previous.assignments.filter((_, assignmentIndex) => assignmentIndex !== index),
    }));
  };

  const toggleTaskLink = (taskId: string) => {
    setForm((previous) => ({
      ...previous,
      linkedTaskIds: previous.linkedTaskIds.includes(taskId)
        ? previous.linkedTaskIds.filter((idValue) => idValue !== taskId)
        : [...previous.linkedTaskIds, taskId],
    }));
  };

  const validateForm = () => {
    if (!form.title.trim()) {
      toast.error("عنوان الهدف مطلوب");
      return false;
    }

    if (!form.targetValue || toNumber(form.targetValue) <= 0) {
      toast.error("القيمة المستهدفة يجب أن تكون أكبر من صفر");
      return false;
    }

    if (!form.startDate || !form.endDate) {
      toast.error("حدد تاريخ البداية والنهاية");
      return false;
    }

    if (new Date(form.startDate) > new Date(form.endDate)) {
      toast.error("تاريخ البداية يجب أن يكون قبل تاريخ النهاية");
      return false;
    }

    if (form.goalType === "PROJECT" && !form.projectId) {
      toast.error("اختر المشروع المرتبط بالهدف");
      return false;
    }

    if (form.goalType === "EMPLOYEE" && !form.employeeId) {
      toast.error("اختر الموظف المسؤول عن الهدف");
      return false;
    }

    if (form.goalType === "DEPARTMENT" && !form.departmentId) {
      toast.error("اختر القسم المسؤول عن الهدف");
      return false;
    }

    if (form.goalType === "PROJECT") {
      const hasValidAssignment = form.assignments.some(
        (assignment) => assignment.employeeId && toNumber(assignment.targetValue) > 0,
      );

      if (!hasValidAssignment) {
        toast.error("أضف على الأقل توزيعًا واحدًا على موظف");
        return false;
      }
    }

    return true;
  };

  const buildPayload = () => {
    const payload: Record<string, unknown> = {
      title: form.title.trim(),
      description: form.description.trim() || null,
      goalType: form.goalType,
      status: form.status,
      priority: form.priority,
      targetValue: toNumber(form.targetValue),
      currentValue: toNumber(form.currentValue),
      unit: form.unit.trim() || null,
      startDate: form.startDate,
      endDate: form.endDate,
      autoGenerateDaily: form.goalType === "EMPLOYEE" ? form.autoGenerateDaily : false,
      linkedTaskIds: form.linkedTaskIds,
    };

    if (form.projectId) {
      payload.projectId = form.projectId;
    }

    if (form.departmentId) {
      payload.departmentId = form.departmentId;
    }

    if (form.employeeId) {
      payload.employeeId = form.employeeId;
    }

    if (form.parentGoalId) {
      payload.parentGoalId = form.parentGoalId;
    }

    if (form.goalType === "PROJECT") {
      payload.assignments = form.assignments
        .filter(
          (assignment) => assignment.employeeId && toNumber(assignment.targetValue) > 0,
        )
        .map((assignment) => ({
          ...(assignment.id ? { id: assignment.id } : {}),
          employeeId: assignment.employeeId,
          title: assignment.title.trim() || form.title.trim(),
          targetValue: toNumber(assignment.targetValue),
          autoGenerateDaily: assignment.autoGenerateDaily,
        }));
    }

    return payload;
  };

  const handleSubmit = async () => {
    if (!validateForm()) {
      return;
    }

    try {
      setLoading(true);
      const payload = buildPayload();

      if (isEdit) {
        await api.put(`/tasks/goals/${id}`, payload);
        toast.success("تم تحديث الهدف بنجاح");
      } else {
        await api.post("/tasks/goals", payload);
        toast.success("تم إنشاء الهدف بنجاح");
      }

      navigate("/goals");
    } catch (error) {
      console.error("Error saving goal:", error);
      toast.error("تعذر حفظ الهدف");
    } finally {
      setLoading(false);
    }
  };

  const handleDelete = async () => {
    if (!isEdit || !id) {
      return;
    }

    if (!window.confirm("هل تريد حذف هذا الهدف وكل الأبناء المرتبطين به؟")) {
      return;
    }

    try {
      setLoading(true);
      await api.delete(`/tasks/goals/${id}`);
      toast.success("تم حذف الهدف");
      navigate("/goals");
    } catch (error) {
      console.error("Error deleting goal:", error);
      toast.error("تعذر حذف الهدف");
    } finally {
      setLoading(false);
    }
  };

  if (fetching) {
    return (
      <div className="flex min-h-[60vh] items-center justify-center">
        <div className="h-12 w-12 animate-spin rounded-full border-b-2 border-primary" />
      </div>
    );
  }

  if (loadError) {
    return (
      <BusinessPageShell className="space-y-6 p-4 md:p-6" dir="rtl">
        <BusinessPageHero
          eyebrow="الأعمال"
          title={isEdit ? "تعذر فتح الهدف" : "تعذر تحميل الصفحة"}
          description="بدل عرض نموذج ناقص، نوضح السبب ونبقي الرجوع سريعًا."
          actions={
            <Button
              variant="outline"
              className="rounded-xl"
              onClick={() => navigate("/goals")}
            >
              <ArrowRight className="ml-2 h-4 w-4" />
              رجوع إلى الأهداف
            </Button>
          }
        />

        <BusinessSectionPanel contentClassName="pt-6">
          <div
            data-testid="goal-load-error-state"
            className="rounded-3xl border border-dashed border-border/70 bg-muted/10 px-6 py-12 text-center"
          >
            <Target className="mx-auto h-10 w-10 text-muted-foreground" />
            <h2 className="mt-4 text-lg font-semibold">{loadError}</h2>
            <p className="mt-2 text-sm text-muted-foreground">
              ارجع إلى قائمة الأهداف لاختيار هدف آخر أو التحقق من الصلاحيات.
            </p>
          </div>
        </BusinessSectionPanel>
      </BusinessPageShell>
    );
  }

  return (
    <BusinessPageShell className="space-y-6 p-4 md:p-6" dir="rtl">
      <BusinessPageHero
        eyebrow="الأعمال"
        title={isEdit ? "تحديث هيكل الهدف" : "بناء هدف جديد"}
        description="من هنا نربط هدف المشروع بالموظفين والمهام والفترة الزمنية، ونحدد هل يتولد منه توزيع يومي تلقائي أم لا."
        actions={
          <div className="flex flex-wrap gap-2">
            {isEdit ? (
              <Button
                variant="outline"
                className="rounded-xl text-destructive"
                data-testid="goal-delete-button"
                onClick={handleDelete}
                disabled={loading}
              >
                <Trash2 className="ml-2 h-4 w-4" />
                حذف
              </Button>
            ) : null}
            <Button
              variant="outline"
              className="rounded-xl"
              onClick={() => navigate("/goals")}
            >
              <ArrowRight className="ml-2 h-4 w-4" />
              رجوع
            </Button>
            <Button
              className="rounded-xl"
              data-testid="goal-save-button"
              onClick={handleSubmit}
              disabled={loading}
            >
              <Save className="ml-2 h-4 w-4" />
              {loading ? "جارٍ الحفظ..." : isEdit ? "حفظ التحديثات" : "إنشاء الهدف"}
            </Button>
          </div>
        }
      />

      <section className="grid gap-4 lg:grid-cols-[minmax(0,1.5fr)_minmax(320px,0.8fr)]">
        <div className="space-y-4">
          <BusinessSectionPanel
            title="تعريف الهدف"
            description="اختر نوع الهدف أولًا، ثم حدّد من يملكه وما الذي سنقيسه فعليًا."
            contentClassName="space-y-5"
          >
            <div className="grid gap-3 md:grid-cols-2 xl:grid-cols-4">
              {GOAL_TYPE_OPTIONS.map((option) => {
                const active = form.goalType === option.value;
                return (
                  <button
                    key={option.value}
                    type="button"
                    onClick={() => setField("goalType", option.value)}
                    className={`rounded-3xl border px-4 py-4 text-right transition-colors ${
                      active
                        ? "border-primary/40 bg-primary/8"
                        : "border-border/70 bg-background hover:border-primary/20"
                    }`}
                  >
                    <div className="text-sm font-semibold">{option.label}</div>
                    <div className="mt-1 text-xs leading-6 text-muted-foreground">
                      {option.hint}
                    </div>
                  </button>
                );
              })}
            </div>

            <div className="grid gap-4 md:grid-cols-2">
              <div className="space-y-2">
                <label className="text-sm font-medium">عنوان الهدف</label>
                <Input
                  data-testid="goal-title-input"
                  value={form.title}
                  onChange={(event) => setField("title", event.target.value)}
                  placeholder="مثال: تحقيق 3000 أوردر خلال الشهر"
                  className="rounded-2xl"
                />
              </div>

              <div className="space-y-2">
                <label className="text-sm font-medium">الوحدة</label>
                <Input
                  value={form.unit}
                  onChange={(event) => setField("unit", event.target.value)}
                  placeholder="طلب / عملية / عقد"
                  className="rounded-2xl"
                />
              </div>
            </div>

            <div className="space-y-2">
              <label className="text-sm font-medium">الوصف</label>
              <Textarea
                value={form.description}
                onChange={(event) => setField("description", event.target.value)}
                placeholder="صف النتيجة المطلوبة وكيف سنعرف أن الهدف تحقق"
                className="min-h-[120px] rounded-2xl"
              />
            </div>

            <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-4">
              <div className="space-y-2">
                <label className="text-sm font-medium">القيمة المستهدفة</label>
                <Input
                  data-testid="goal-target-input"
                  type="number"
                  min="0"
                  value={form.targetValue}
                  onChange={(event) => setField("targetValue", event.target.value)}
                  className="rounded-2xl"
                />
              </div>

              <div className="space-y-2">
                <label className="text-sm font-medium">القيمة الحالية</label>
                <Input
                  type="number"
                  min="0"
                  value={form.currentValue}
                  onChange={(event) => setField("currentValue", event.target.value)}
                  className="rounded-2xl"
                />
              </div>

              <div className="space-y-2">
                <label className="text-sm font-medium">الحالة</label>
                <select
                  value={form.status}
                  onChange={(event) => setField("status", event.target.value as GoalStatus)}
                  className="h-10 w-full rounded-2xl border border-input bg-background px-3 text-sm"
                >
                  {STATUS_OPTIONS.map((option) => (
                    <option key={option.value} value={option.value}>
                      {option.label}
                    </option>
                  ))}
                </select>
              </div>

              <div className="space-y-2">
                <label className="text-sm font-medium">الأولوية</label>
                <select
                  value={form.priority}
                  onChange={(event) =>
                    setField("priority", event.target.value as GoalPriority)
                  }
                  className="h-10 w-full rounded-2xl border border-input bg-background px-3 text-sm"
                >
                  {PRIORITY_OPTIONS.map((option) => (
                    <option key={option.value} value={option.value}>
                      {option.label}
                    </option>
                  ))}
                </select>
              </div>
            </div>

            <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-4">
              <div className="space-y-2">
                <label className="text-sm font-medium">تاريخ البداية</label>
                <Input
                  data-testid="goal-start-date-input"
                  type="date"
                  value={form.startDate}
                  onChange={(event) => setField("startDate", event.target.value)}
                  className="rounded-2xl"
                />
              </div>

              <div className="space-y-2">
                <label className="text-sm font-medium">تاريخ النهاية</label>
                <Input
                  data-testid="goal-end-date-input"
                  type="date"
                  value={form.endDate}
                  onChange={(event) => setField("endDate", event.target.value)}
                  className="rounded-2xl"
                />
              </div>

              <div className="space-y-2">
                <label className="text-sm font-medium">المشروع</label>
                <select
                  data-testid="goal-project-select"
                  value={form.projectId}
                  onChange={(event) => setField("projectId", event.target.value)}
                  className="h-10 w-full rounded-2xl border border-input bg-background px-3 text-sm"
                >
                  <option value="">بدون مشروع</option>
                  {projects.map((project) => (
                    <option key={project.id} value={project.id}>
                      {project.name}
                    </option>
                  ))}
                </select>
              </div>

              <div className="space-y-2">
                <label className="text-sm font-medium">الهدف الأب</label>
                <select
                  value={form.parentGoalId}
                  onChange={(event) => setField("parentGoalId", event.target.value)}
                  className="h-10 w-full rounded-2xl border border-input bg-background px-3 text-sm"
                >
                  <option value="">بدون هدف أب</option>
                  {availableParentGoals.map((goal) => (
                    <option key={goal.id} value={goal.id}>
                      {goal.title}
                    </option>
                  ))}
                </select>
              </div>
            </div>

            {form.goalType === "EMPLOYEE" ? (
              <div className="grid gap-4 md:grid-cols-[minmax(0,1fr)_auto]">
                <div className="space-y-2">
                  <label className="text-sm font-medium">الموظف المسؤول</label>
                  <select
                    value={form.employeeId}
                    onChange={(event) => setField("employeeId", event.target.value)}
                    className="h-10 w-full rounded-2xl border border-input bg-background px-3 text-sm"
                  >
                    <option value="">اختر الموظف</option>
                    {employees.map((employee) => (
                      <option key={employee.id} value={employee.id}>
                        {getEmployeeLabel(employee)}
                      </option>
                    ))}
                  </select>
                </div>

                <div className="flex items-end justify-between gap-3 rounded-2xl border border-border/70 bg-muted/20 px-4 py-3">
                  <div>
                    <div className="text-sm font-medium">توليد أهداف يومية</div>
                    <div className="text-xs text-muted-foreground">
                      يوزع الهدف تلقائيًا على أيام العمل.
                    </div>
                  </div>
                  <Switch
                    data-testid="goal-auto-daily-switch"
                    checked={form.autoGenerateDaily}
                    onCheckedChange={(checked) =>
                      setField("autoGenerateDaily", Boolean(checked))
                    }
                  />
                </div>
              </div>
            ) : null}

            {form.goalType === "DEPARTMENT" ? (
              <div className="space-y-2">
                <label className="text-sm font-medium">القسم المسؤول</label>
                <select
                  value={form.departmentId}
                  onChange={(event) => setField("departmentId", event.target.value)}
                  className="h-10 w-full rounded-2xl border border-input bg-background px-3 text-sm"
                >
                  <option value="">اختر القسم</option>
                  {departments.map((department) => (
                    <option key={department.id} value={department.id}>
                      {department.name}
                    </option>
                  ))}
                </select>
              </div>
            ) : null}
          </BusinessSectionPanel>

          {form.goalType === "PROJECT" ? (
            <BusinessSectionPanel
              title="توزيع الهدف على الفريق"
              description="كل توزيع هنا ينشئ هدف ابن لموظف، ويمكن لكل واحد منهم توليد أهداف يومية تلقائيًا."
              contentClassName="space-y-4"
            >
              <div className="rounded-3xl border border-border/70 bg-muted/15 p-4">
                <div className="flex flex-wrap items-center justify-between gap-3 text-sm">
                  <div>
                    <div className="font-medium">إجمالي التوزيع</div>
                    <div className="text-muted-foreground">
                      تم توزيع {assignmentTargetTotal.toLocaleString("ar-EG")} من أصل{" "}
                      {targetValueNumber.toLocaleString("ar-EG")}
                    </div>
                  </div>
                  <Badge variant="outline" className="rounded-full">
                    المتبقي{" "}
                    {Math.max(0, targetValueNumber - assignmentTargetTotal).toLocaleString(
                      "ar-EG",
                    )}
                  </Badge>
                </div>
                <Progress value={assignmentCoverage} className="mt-3" />
              </div>

              <div className="space-y-3">
                {form.assignments.map((assignment, index) => (
                  <div
                    key={`${assignment.id || "new"}-${index}`}
                    className="rounded-3xl border border-border/70 bg-background p-4"
                  >
                    <div className="grid gap-3 xl:grid-cols-[minmax(0,1.1fr)_minmax(0,1fr)_180px_auto]">
                      <div className="space-y-2">
                        <label className="text-xs font-medium text-muted-foreground">
                          الموظف
                        </label>
                        <select
                          data-testid={`goal-assignment-employee-${index}`}
                          value={assignment.employeeId}
                          onChange={(event) =>
                            updateAssignment(index, "employeeId", event.target.value)
                          }
                          className="h-10 w-full rounded-2xl border border-input bg-background px-3 text-sm"
                        >
                          <option value="">اختر الموظف</option>
                          {employees.map((employee) => (
                            <option key={employee.id} value={employee.id}>
                              {getEmployeeLabel(employee)}
                            </option>
                          ))}
                        </select>
                      </div>

                      <div className="space-y-2">
                        <label className="text-xs font-medium text-muted-foreground">
                          عنوان هدف الموظف
                        </label>
                        <Input
                          value={assignment.title}
                          onChange={(event) =>
                            updateAssignment(index, "title", event.target.value)
                          }
                          placeholder="يترك فارغًا ليأخذ نفس عنوان الهدف الأب"
                          className="rounded-2xl"
                        />
                      </div>

                      <div className="space-y-2">
                        <label className="text-xs font-medium text-muted-foreground">
                          المستهدف
                        </label>
                        <Input
                          data-testid={`goal-assignment-target-${index}`}
                          type="number"
                          min="0"
                          value={assignment.targetValue}
                          onChange={(event) =>
                            updateAssignment(index, "targetValue", event.target.value)
                          }
                          className="rounded-2xl"
                        />
                      </div>

                      <div className="flex items-end gap-2">
                        <div className="flex flex-1 items-center justify-between rounded-2xl border border-border/70 px-3 py-2">
                          <div className="text-xs">
                            <div className="font-medium">يومي تلقائي</div>
                            <div className="text-muted-foreground">يولد أهداف يومية</div>
                          </div>
                          <Switch
                            data-testid={`goal-assignment-auto-daily-${index}`}
                            checked={assignment.autoGenerateDaily}
                            onCheckedChange={(checked) =>
                              updateAssignment(
                                index,
                                "autoGenerateDaily",
                                Boolean(checked),
                              )
                            }
                          />
                        </div>
                        <Button
                          type="button"
                          variant="outline"
                          className="rounded-2xl text-destructive"
                          onClick={() => removeAssignment(index)}
                        >
                          <Trash2 className="h-4 w-4" />
                        </Button>
                      </div>
                    </div>
                  </div>
                ))}
              </div>

              <Button type="button" variant="outline" className="rounded-xl" onClick={addAssignment}>
                <Plus className="ml-2 h-4 w-4" />
                إضافة توزيع جديد
              </Button>
            </BusinessSectionPanel>
          ) : null}

          <BusinessSectionPanel
            title="المهام المرتبطة"
            description="اربط المهام التي تمثل تنفيذًا مباشرًا لهذا الهدف. يمكن أن تكون مهام زمنية أو عددية."
            contentClassName="space-y-4"
          >
            <Input
              value={taskSearch}
              onChange={(event) => setTaskSearch(event.target.value)}
              placeholder="ابحث عن مهمة بالعنوان"
              className="rounded-2xl"
            />

            {filteredTaskOptions.length === 0 ? (
              <div className="rounded-3xl border border-dashed border-border/70 bg-muted/10 px-4 py-8 text-center text-sm text-muted-foreground">
                لا توجد مهام مطابقة للفلتر الحالي.
              </div>
            ) : (
              <div className="grid gap-3 lg:grid-cols-2">
                {filteredTaskOptions.slice(0, 16).map((task) => {
                  const selected = form.linkedTaskIds.includes(task.id);
                  return (
                    <button
                      key={task.id}
                      type="button"
                      onClick={() => toggleTaskLink(task.id)}
                      className={`rounded-3xl border p-4 text-right transition-colors ${
                        selected
                          ? "border-primary/40 bg-primary/8"
                          : "border-border/70 bg-background hover:border-primary/20"
                      }`}
                    >
                      <div className="flex items-start justify-between gap-3">
                        <div>
                          <div className="font-medium">{task.title}</div>
                          <div className="mt-1 text-xs text-muted-foreground">
                            {task.measurementType === "COUNT"
                              ? "مهمة بعدّاد إنجاز"
                              : task.measurementType === "VALUE"
                                ? "مهمة بقياس قيمة"
                                : "مهمة زمنية"}
                          </div>
                        </div>
                        <CheckSquare
                          className={`h-5 w-5 ${
                            selected ? "text-primary" : "text-muted-foreground"
                          }`}
                        />
                      </div>

                      {task.metricTargetValue !== null && task.metricTargetValue !== undefined ? (
                        <div className="mt-3 text-xs text-muted-foreground">
                          المستهدف داخل المهمة:{" "}
                          {Number(task.metricTargetValue).toLocaleString("ar-EG")}
                        </div>
                      ) : null}
                    </button>
                  );
                })}
              </div>
            )}
          </BusinessSectionPanel>
        </div>

        <div className="space-y-4">
          <BusinessSectionPanel
            title="ملخص الهدف"
            description="قراءة سريعة قبل الحفظ."
            contentClassName="space-y-4"
          >
            <div className="grid gap-3">
              <div className="rounded-3xl border border-border/70 bg-background p-4">
                <div className="flex items-center gap-2 text-sm text-muted-foreground">
                  <Target className="h-4 w-4" />
                  التقدم الحالي
                </div>
                <div className="mt-2 text-3xl font-semibold">
                  {targetValueNumber > 0
                    ? `${Math.min(
                        100,
                        (toNumber(form.currentValue || "0") / targetValueNumber) * 100,
                      ).toFixed(1)}%`
                    : "0%"}
                </div>
                <Progress
                  value={
                    targetValueNumber > 0
                      ? Math.min(
                          100,
                          (toNumber(form.currentValue || "0") / targetValueNumber) * 100,
                        )
                      : 0
                  }
                  className="mt-3"
                />
              </div>

              <div className="rounded-3xl border border-border/70 bg-background p-4">
                <div className="flex items-center gap-2 text-sm text-muted-foreground">
                  <CalendarRange className="h-4 w-4" />
                  الفترة
                </div>
                <div className="mt-2 text-sm font-medium">
                  {form.startDate || "غير محدد"} - {form.endDate || "غير محدد"}
                </div>
              </div>

              <div className="rounded-3xl border border-border/70 bg-background p-4">
                <div className="flex items-center gap-2 text-sm text-muted-foreground">
                  <FolderKanban className="h-4 w-4" />
                  المهام المرتبطة
                </div>
                <div className="mt-2 text-2xl font-semibold">{linkedTasks.length}</div>
              </div>

              <div className="rounded-3xl border border-border/70 bg-background p-4">
                <div className="flex items-center gap-2 text-sm text-muted-foreground">
                  <Users className="h-4 w-4" />
                  الأبناء الحاليون
                </div>
                <div className="mt-2 text-2xl font-semibold">
                  {form.goalType === "PROJECT"
                    ? form.assignments.filter((assignment) => assignment.employeeId).length
                    : goalDetails?.childGoals?.length || 0}
                </div>
              </div>
            </div>
          </BusinessSectionPanel>

          <BusinessSectionPanel
            title="شبكة العلاقة"
            description="من يملك الهدف وإلى أين يرفع التحديث."
            contentClassName="space-y-3"
          >
              <div className="rounded-3xl border border-border/70 bg-muted/15 p-4">
                <div className="flex items-center gap-2 text-sm text-muted-foreground">
                  <Briefcase className="h-4 w-4" />
                  المالك
                </div>
              <div className="mt-2 text-sm font-medium">
                {form.goalType === "PROJECT" && form.projectId
                  ? projects.find((project) => project.id === form.projectId)?.name ||
                    "مشروع غير محدد"
                  : form.goalType === "EMPLOYEE" && form.employeeId
                    ? getEmployeeLabel(
                        employees.find((employee) => employee.id === form.employeeId) || {
                          id: "",
                          firstName: "موظف",
                          lastName: "",
                        },
                      )
                    : form.goalType === "DEPARTMENT" && form.departmentId
                      ? departments.find((department) => department.id === form.departmentId)
                          ?.name || "قسم غير محدد"
                      : "على مستوى الشركة"}
              </div>
            </div>

            <div className="rounded-3xl border border-border/70 bg-muted/15 p-4">
              <div className="flex items-center gap-2 text-sm text-muted-foreground">
                <UserRound className="h-4 w-4" />
                الهدف الأب
              </div>
              <div className="mt-2 text-sm font-medium">
                {availableParentGoals.find((goal) => goal.id === form.parentGoalId)?.title ||
                  "لا يوجد هدف أب"}
              </div>
            </div>

            {isEdit && goalDetails?.childGoals?.length ? (
              <div className="rounded-3xl border border-border/70 bg-muted/15 p-4">
                <div className="mb-3 text-sm font-medium">أهداف الابن الحالية</div>
                <div className="space-y-2">
                  {goalDetails.childGoals.slice(0, 5).map((childGoal) => (
                    <div
                      key={childGoal.id}
                      className="flex items-center justify-between rounded-2xl bg-background px-3 py-2 text-sm"
                    >
                      <span>{childGoal.title}</span>
                      <span className="text-muted-foreground">
                        {Number(childGoal.targetValue || 0).toLocaleString("ar-EG")}
                      </span>
                    </div>
                  ))}
                </div>
              </div>
            ) : null}
          </BusinessSectionPanel>
        </div>
      </section>
    </BusinessPageShell>
  );
};

export default CreateGoal;
