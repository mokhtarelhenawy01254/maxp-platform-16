'use strict';

/**
 * aiReplySanitizer.js
 *
 * Ensures AI responses never leak ugly raw image URLs into customer chats.
 * Extracts any image URLs into structured media attachments (for Facebook/WhatsApp)
 * and cleanses the text so customer receives natural conversational text + native images.
 */

const IMAGE_URL_REGEX = /(?:https?:\/\/[^\s)\]<>"'`]+\.(?:jpe?g|png|webp|gif)(?:\?[^\s)\]<>"'`]*)?)|(?:\/uploads\/[^\s)\]<>"'`]+\.(?:jpe?g|png|webp|gif)(?:\?[^\s)\]<>"'`]*)?)/gi;
const MARKDOWN_IMAGE_REGEX = /!\[.*?\]\([^\)]+\)/g;
const MARKDOWN_LINK_IMAGE_REGEX = /\[.*?\]\((?:https?:\/\/|\/uploads\/)[^\)]+\.(?:jpe?g|png|webp|gif)[^\)]*\)/gi;

function getBaseApiUrl() {
  return (process.env.MAXP_API_URL || process.env.BASE_URL || 'https://mokhtarelhenawy.online').replace(/\/+$/, '');
}

/**
 * Sanitizes an AI reply text and populates attachments.
 *
 * @param {string} rawReplyText - Raw text generated by AI model.
 * @param {Array} [initialAttachments=[]] - Existing attachments from AI response.
 * @returns {{ cleanedText: string, attachments: Array }}
 */
function sanitizeAiReply(rawReplyText, initialAttachments = []) {
  const attachments = Array.isArray(initialAttachments) ? [...initialAttachments] : [];
  if (!rawReplyText || typeof rawReplyText !== 'string') {
    return { cleanedText: rawReplyText || '', attachments };
  }

  const baseUrl = getBaseApiUrl();

  // 1. Extract all image URLs from raw text
  const matches = rawReplyText.match(IMAGE_URL_REGEX) || [];
  for (const rawUrl of matches) {
    const fullUrl = rawUrl.startsWith('/') ? `${baseUrl}${rawUrl}` : rawUrl;
    if (!attachments.some(a => a && a.url === fullUrl)) {
      attachments.push({
        type: 'image',
        url: fullUrl,
        source: 'reply_extraction'
      });
    }
  }

  // 2. Strip markdown image tags ![alt](url)
  let cleaned = rawReplyText.replace(MARKDOWN_IMAGE_REGEX, '');

  // 3. Strip markdown links to images [caption](url)
  cleaned = cleaned.replace(MARKDOWN_LINK_IMAGE_REGEX, '');

  // 4. Strip raw image URLs
  cleaned = cleaned.replace(IMAGE_URL_REGEX, '');

  // 5. Clean orphaned pointers (e.g. lines that just had an arrow pointing down to a link)
  cleaned = cleaned
    .split('\n')
    .map(line => {
      const trimmed = line.trim();
      if (trimmed === '👇' || trimmed === '⬇️' || trimmed === '👇🏻' || trimmed === '👇🏼' || trimmed === '👇🏽') {
        return '';
      }
      return line;
    })
    .join('\n');

  // 6. Anti-Prompt Leakage & Robotic meta-talk cleansing
  // Replaces internal safety refusals ("مش هخمن لحضرتك") with natural human courtesies
  // and strips robotic self-identifications.
  const LEAKAGE_RULES = [
    {
      regex: /(?:وأكيد\s+|أكيد\s+)?(?:مش\s+هخمّ?ن\s+لحضرتك|مش\s+مسموح\s*(?:لي|لى)\s*(?:أخمن|بالتخمين)|ممنوع\s*أخمن)/gi,
      replacement: 'خليني أتأكد لحضرتك من الإدارة وأرجعلك بالتفاصيل حالاً'
    },
    {
      regex: /(?:بصفتي|كنموذج|لأني|باعتباري)\s+(?:ذكاء\s+اصطناعي|نموذج\s+لغوي|روبوت|مساعد\s+افتراضي|نظام\s+آلي)/gi,
      replacement: ''
    },
    {
      regex: /(?:أنا|انني|أنني)\s+(?:ذكاء\s+اصطناعي|نموذج\s+لغوي|روبوت|مساعد\s+افتراضي|نظام\s+آلي|برنامج\s+كمبيوتر)/gi,
      replacement: 'أنا هنا لمساعدتك'
    },
    {
      regex: /\b(?:As an AI(?:\s+language\s+model)?|I am an AI(?:\s+language\s+model)?)\b/gi,
      replacement: ''
    },
    {
      regex: /(?:حسب|وفقاً\s+لـ?|طبقاً\s+لـ?|بناءً\s+على)\s+(?:تعليماتي|التعليمات\s+المعطاة\s+لي|السياسة\s+المحددة\s+لي|الأوامر\s+المحددة\s+لي)/gi,
      replacement: ''
    }
  ];

  for (const rule of LEAKAGE_RULES) {
    cleaned = cleaned.replace(rule.regex, rule.replacement);
  }

  // 7. Clean orphaned punctuation at line starts or redundant commas
  cleaned = cleaned.replace(/^[\s,،.؛;]+/gm, '');
  cleaned = cleaned.replace(/[\s,،]+([,،.؛])/g, '$1');

  // 8. Collapse excessive blank lines and clean redundant spaces
  cleaned = cleaned.replace(/[ \t]+/g, ' ');
  cleaned = cleaned.replace(/\n\s*\n\s*\n+/g, '\n\n').trim();

  return {
    cleanedText: cleaned,
    attachments
  };
}

module.exports = {
  sanitizeAiReply,
  IMAGE_URL_REGEX,
};
