const fs = require('fs');
const path = require('path');

const TRANSLATION_PATH = path.join(__dirname, '../apps/frontend/src/locales/en/translation.json');
const OUTPUT_PATH = path.join(__dirname, '../apps/frontend/src/types/i18n-resources.d.ts');

function flattenKeys(obj, prefix = '') {
  let keys = [];
  for (const key in obj) {
    const fullKey = prefix ? `${prefix}.${key}` : key;
    if (typeof obj[key] === 'object' && obj[key] !== null && !Array.isArray(obj[key])) {
      keys = keys.concat(flattenKeys(obj[key], fullKey));
    } else {
      keys.push(fullKey);
    }
  }
  return keys;
}

function generateNestedType(obj, indent = '  ') {
  const lines = [];
  for (const key in obj) {
    const val = obj[key];
    const safeKey = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(key) ? key : `'${key}'`;
    if (typeof val === 'object' && val !== null && !Array.isArray(val)) {
      lines.push(`${indent}${safeKey}: {`);
      lines.push(generateNestedType(val, indent + '  '));
      lines.push(`${indent}};`);
    } else {
      lines.push(`${indent}${safeKey}: string;`);
    }
  }
  return lines.join('\n');
}

function generate() {
  const raw = fs.readFileSync(TRANSLATION_PATH, 'utf-8');
  const data = JSON.parse(raw);

  const content = `// Auto-generated by scripts/generate-i18n-types.js
// Do not edit manually — run \`npm run i18n:types\` to regenerate

declare module 'react-i18next' {
  interface Resources {
    translation: {
      ${generateNestedType(data, '      ')}
    };
  }
}

export {};
`;

  fs.writeFileSync(OUTPUT_PATH, content, 'utf-8');
  const keyCount = flattenKeys(data).length;
  console.log(`✓ Generated i18n TypeScript types: ${OUTPUT_PATH}`);
  console.log(`  ${keyCount} keys mapped`);
}

generate();
