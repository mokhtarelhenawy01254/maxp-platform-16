export const getAppById = (id: string): AppDefinition | undefined => {
  return APP_REGISTRY.find((app) => app.id === id);
};

export const getAppsByCategory = (category: AppCategory): AppDefinition[] => {
  return APP_REGISTRY.filter((app) => app.category === category);
};

export const getVisibleApps = (
  userRole: string | undefined,
  activeApps: string[],
): AppDefinition[] => {
  return APP_REGISTRY.filter((app) => {
    if (app.isHidden) return false;

    if (app.requiredRoles && app.requiredRoles.length > 0) {
      if (!userRole || !app.requiredRoles.includes(userRole)) return false;
    }

    if (app.requiredApps && app.requiredApps.length > 0) {
      const hasRequired = app.requiredApps.some((slug) =>
        activeApps.some((a) => a.toLowerCase() === slug.toLowerCase()),
      );
      if (!hasRequired) return false;
    }

    return true;
  });
};
