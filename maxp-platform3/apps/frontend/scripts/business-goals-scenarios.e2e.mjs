const recalculateGoalStats = (state) => {
  state.goalStats.total = state.goals.length;
  state.goalStats.completed = state.goals.filter(
    (goal) => goal.status === "COMPLETED",
  ).length;
  state.goalStats.completionRate =
    state.goalStats.total > 0
      ? Number(
          (
            (state.goalStats.completed / state.goalStats.total) *
            100
          ).toFixed(1),
        )
      : 0;
  state.goalStats.averageProgress =
    state.goals.length > 0
      ? Number(
          (
            state.goals.reduce(
              (sum, goal) => sum + Number(goal.progress || 0),
              0,
            ) / state.goals.length
          ).toFixed(1),
        )
      : 0;
};

const getFilteredGoals = (state, searchParams) => {
  const includeDaily = searchParams.get("includeDaily");
  const goalType = searchParams.get("goalType");
  const status = searchParams.get("status");
  const projectId = searchParams.get("projectId");

  return state.goals.filter((goal) => {
    if (includeDaily === "false" && goal.goalType === "DAILY") {
      return false;
    }

    if (goalType && goal.goalType !== goalType) {
      return false;
    }

    if (status && goal.status !== status) {
      return false;
    }

    if (projectId && goal.project?.id !== projectId) {
      return false;
    }

    return true;
  });
};

